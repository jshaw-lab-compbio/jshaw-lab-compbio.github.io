#!/usr/bin/env python3
"""Refresh _data/conda_downloads.yml with total Bioconda download counts.

Reads the `conda:` package name of each tool in _data/software.yml and asks
the anaconda.org API for its downloads (summed over all versions/platforms).
Run by .github/workflows/conda-downloads.yml weekly; can also be run by hand.
A package that fails to fetch keeps its previous count.
"""
import json
import re
import urllib.request
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "_data"
OUT = DATA / "conda_downloads.yml"

packages = re.findall(r'^\s+conda:\s*"?([\w.-]+)"?\s*$', (DATA / "software.yml").read_text(), re.M)
counts = dict(re.findall(r"^([\w.-]+):\s*(\d+)\s*$", OUT.read_text(), re.M)) if OUT.exists() else {}

for pkg in packages:
    try:
        with urllib.request.urlopen(f"https://api.anaconda.org/package/bioconda/{pkg}", timeout=30) as r:
            counts[pkg] = sum(f.get("ndownloads", 0) for f in json.load(r)["files"])
    except Exception as e:
        print(f"warning: could not fetch {pkg}: {e}")

lines = ["# Generated by scripts/update_conda_downloads.py — do not edit by hand."]
lines += [f"{pkg}: {counts[pkg]}" for pkg in packages if pkg in counts]
OUT.write_text("\n".join(lines) + "\n")
print(OUT.read_text())
